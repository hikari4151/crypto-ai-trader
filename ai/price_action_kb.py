"""价格行为专业知识库：从 AL Brooks《价格行为交易》（趋势篇/反转篇）提炼的分析框架。

用途：注入 AI 行情解读提示词，让 AI 用专业价格行为（Price Action）视角解读行情，
而不是只罗列指标。所有知识点来自用户知识库《价格行为》系列书籍。

这些知识是**交易分析框架**，不是可执行指令——AI 需结合当前行情快照灵活运用。
"""
from typing import Optional

# ============ 知识库来源信息 ============
SOURCE_INFO = (
    "【价格行为专业知识（来源：AL Brooks《价格行为交易》趋势篇/反转篇）】"
)

# ============ 核心分析框架（分模块，按需拼接） ============

# 1. 趋势结构
TREND_FRAME = (
    "1. 趋势结构：\n"
    "· 多头趋势 = 依次抬高的高点和低点（HH/HL）；空头趋势 = 依次降低的高点和低点（LH/LL）。\n"
    "· 趋势中的回撤是反方向的微型趋势，交易者预期它很快结束、主要趋势将恢复；"
    "回撤幅度小（≤2-3 根K线）说明趋势强劲（强势多方在回撤时买进）。\n"
    "· 趋势结束时，最后一个旗形/回撤常失败，然后趋势转为交易区间，最终可能反转。\n"
    "· 强趋势中的顺势交易对信号棒要求低（几乎任何理由做多都行），"
    "逆势交易对信号棒要求高（需要强势反转信号棒）。\n"
    "· 判断趋势时不要依赖单一指标背离——背离只是辅助，真正的证据是趋势线被突破后"
    "对极点的测试是否守住（测试旧极点反转=趋势延续，跌破=趋势反转）。"
)

# 2. 突破与反转
BREAKOUT_FRAME = (
    "2. 突破与反转：\n"
    "· 每条趋势棒都是一次突破，突破后市场常常尝试令突破失败并反转。"
    "若突破比反转尝试强（两条尾线短的大趋势棒 + 一根小十字星），反转常失败，"
    "失败的反转会成为新趋势中的旗形起点（突破回撤买进架构）。\n"
    "· 向上突破重要高点后，若下一棒是内包棒（未创新高）且再下一棒跌破其低点，"
    "突破失败、反转下跌的几率大增。\n"
    "· 突破后价格常被吸引至测量运动目标（磁力位），在磁力位附近可能反转。\n"
    "· 交易区间突破后常形成通道，通道通常在测量运动区附近停止，然后回到交易区间。"
)

# 3. 高潮与反转形态
CLIMAX_FRAME = (
    "3. 高潮与反转形态：\n"
    "· 高潮 = 不能持续的价格行为：连续多根趋势棒（低点高点都低于前一棒/高于前一棒）"
    "或宽幅趋势棒。高潮之后常伴随至少两条腿的回调/横盘。\n"
    "· 双棒反转是最常见的反转架构：相邻两根方向相反的趋势棒（如空头棒+强多头棒）。\n"
    "· 卖出高潮（强空头趋势末端的宽幅空头棒）常引发两条腿横盘到向上回调，"
    "不常立即趋势反转；在强空头趋势中首次反转买进较冒险。\n"
    "· 内包棒、外包棒、十字星都可作为信号棒；信号棒后的强势入场棒是信号确认。\n"
    "· 趋势末期的高潮宽幅棒常是最后一批追势者入场，之后市场进入交易区间。"
)

# 4. 支撑阻力与关键位
SR_FRAME = (
    "4. 支撑阻力与关键位：\n"
    "· 支撑/阻力位是「磁力位」：价格常被吸引测试它们，并在附近反转或突破。\n"
    "· 测试旧极点的结果决定趋势延续或反转：守住极点后反转=高胜率架构；"
    "突破极点且坚持=趋势延续。\n"
    "· 交易区间是更高时间框架趋势中的回撤；区间内的每条腿都是小趋势。\n"
    "· 关键位附近的K线行为（触及次数、放量、假突破）比单纯的价格水平更重要。"
)

# 5. 心理与执行
PSYCH_FRAME = (
    "5. 交易心理与执行：\n"
    "· 顺势交易总是更明智的选择：与信号棒方向一致的趋势棒入场成功率最高。\n"
    "· 等待信号棒之外的止损入场需要市场朝你方向运动更多，增加成功率。\n"
    "· 信号棒是十字星或与交易方向相反的趋势棒时，失败几率较高。\n"
    "· 关注价格行为而不是盈亏：不断研判下一棒/下几棒为什么可能上涨或下跌。"
)

_ALL_BLOCKS = [TREND_FRAME, BREAKOUT_FRAME, CLIMAX_FRAME, SR_FRAME, PSYCH_FRAME]


def price_action_knowledge(compact: bool = False) -> str:
    """拼接价格行为专业知识块，供 AI 行情解读提示词使用。

    compact=True 时返回精简版（约 600 字，避免过长稀释主指令）。
    """
    if compact:
        return (
            SOURCE_INFO + "\n" +
            "· 趋势 = 依次抬高的HH/HL（多头）或降低的LH/LL（空头）；回撤是微型反向趋势，"
            "强趋势回撤浅（≤2-3棒）。顺势交易对信号棒要求低，逆势要求高。\n"
            "· 每条趋势棒都是突破，突破后常尝试反转；若突破强于反转尝试（大趋势棒+小十字星），"
            "失败的反转成为旗形（突破回撤买进）。向上突破后内包棒+跌破低点=突破失败反转几率大增。\n"
            "· 高潮=不能持续的行为（连续同向趋势棒/宽幅趋势棒），之后常两腿回调；"
            "双棒反转是最常见反转架构。\n"
            "· 支撑阻力是磁力位，价格常被吸引测试；测试旧极点守住=趋势延续，跌破=反转。"
            "关键位附近的K线行为（触及次数/放量/假突破）比价位本身更重要。\n"
            "· 背离只是辅助证据，真正的反转判断依据是趋势线突破后对极点的测试结果；"
            "不要仅凭背离下注。"
        )
    return SOURCE_INFO + "\n\n" + "\n\n".join(_ALL_BLOCKS)


def add_price_action_knowledge(system_prompt: str, compact: bool = True) -> str:
    """把价格行为知识注入系统提示词（在末尾追加，避免干扰主指令）。"""
    kb = price_action_knowledge(compact=compact)
    if kb in system_prompt:
        return system_prompt
    return system_prompt.rstrip() + "\n\n" + kb
